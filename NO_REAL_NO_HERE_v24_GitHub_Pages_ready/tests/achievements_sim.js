'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { LEVELS } = require('../shared/levels.js');
const source = fs.readFileSync(require.resolve('../src/main.js'), 'utf8');
const match = source.match(/achievementIndex\(id\)\{([\s\S]*?)\},\n recordLevelEscape/);
assert.ok(match, 'achievementIndex method exists');
const indexFn = vm.runInNewContext(`(function(Levels){return function(id){${match[1]}}})`)({ defs: LEVELS });
const expected = [...Array.from({length:10},(_,i)=>'level'+i), 'level9b', ...Array.from({length:21},(_,i)=>'level'+(i+10)), 'void','sanctuary','glitchshop'];
assert.equal(expected.length, 35, 'level escape map has exactly 35 slots');
assert.equal(Object.keys(LEVELS).length, 35, 'project defines 35 levels');
assert.deepEqual(expected.map(id => indexFn(id)), Array.from({length:35},(_,i)=>i), 'every level maps to a unique index');
for (const id of Object.keys(LEVELS)) assert.ok(indexFn(id) >= 0 && indexFn(id) < 35, `${id} maps to a level achievement`);
assert.equal(indexFn('missing-level'), -1, 'unknown levels do not unlock achievements');
const namesMatch = source.match(/achievementNames\(\)\{return (\[[^;]+\]);\}/);
assert.ok(namesMatch, 'achievementNames exists');
const names = vm.runInNewContext(namesMatch[1]);
assert.equal(names.length, 46, 'exactly 46 achievement names exist');
assert.equal(names[35], '새로운 느낌', 'achievement 36 name');
assert.equal(names[36], '오^#ㄹ^#2ㅠ', 'achievement 37 name preserved exactly');
assert.equal(names[37], '엔딩을 목격하다', 'achievement 38 name');
assert.ok(source.includes("recordAchievement(37,'상점 입장')"), 'shop entry awards achievement 37');
assert.ok(source.includes("this.recordAchievement(38,'첫 엔딩 보기')"), 'first ending awards achievement 38');
assert.ok(source.includes('const endingAch={true:39,alone:40,loop:41,sacrifice:42,guardian:43,truth:44,corrupt:45,fake:46}'), 'each ending has its own achievement');
assert.ok(source.includes("name:'🌈 무지개 슈트 (전체 엔딩 달성 보상)'"), 'rainbow suit reward exists');
assert.ok(source.includes('const allClear=allEndingKeys.every(k=>Save.data.endings[k])'), 'rainbow suit unlocks after all endings cumulatively');
assert.ok(fs.readFileSync(require.resolve('../src/net.js'), 'utf8').includes("Game.recordAchievement(36,'십자가로 부활')"), 'being revived by cross awards achievement 36');
assert.ok(source.includes("if(Game.mode!=='sp')return"), 'multiplayer exits do not unlock solo level escape achievements');
const recMatch = source.match(/recordLevelEscape\(id\)\{([\s\S]*?)\},\n recordAchievement/);
assert.ok(recMatch, 'recordLevelEscape method exists');
const specialMatch = source.match(/recordAchievement\(number,description\)\{([\s\S]*?)\},\n achievements/);
assert.ok(specialMatch, 'recordAchievement method exists');
const mock = {mode:'sp', achievementIndex:indexFn, achievementNames:()=>names, recordAchievement:null};
const saved = {data:{ach:{},wallet:0,total:0,diff:'normal'}, saves:0, save(){this.saves++}};
const messages=[];
const context={Date, Game:mock, Save:saved, UI:{toast:(m)=>messages.push(m)}};
mock.recordAchievement=vm.runInNewContext(`(function(number,description){${specialMatch[1]}})`, context);
const recordEscape=vm.runInNewContext(`(function(id){${recMatch[1]}})`, context);
recordEscape.call(mock,'level9');
assert.equal(saved.data.ach.level_escape_10.name,names[9],'level9 unlocks achievement 10');
recordEscape.call(mock,'level9b');
assert.equal(saved.data.ach.level_escape_11.name,names[10],'level9b unlocks a distinct achievement 11');
recordEscape.call(mock,'level9b');
assert.equal(Object.keys(saved.data.ach).length,2,'repeated exits do not duplicate achievement records');
mock.recordAchievement.call(mock,36,'십자가로 부활');
mock.recordAchievement.call(mock,37,'상점 입장');
mock.recordAchievement.call(mock,38,'엔딩 보기');
assert.equal(saved.data.ach.level_escape_36.name,'새로운 느낌','cross revival award saved');
assert.equal(saved.data.ach.level_escape_37.name,'오^#ㄹ^#2ㅠ','shop entry award saved');
assert.equal(saved.data.ach.level_escape_38.name,'엔딩을 목격하다','ending-view award saved');
mock.recordAchievement.call(mock,36,'십자가로 부활');
assert.equal(Object.keys(saved.data.ach).length,5,'repeated special achievements do not duplicate records');
assert.equal(saved.saves,5,'each new achievement saves once');
assert.equal(saved.data.wallet,25,'normal difficulty grants 5 coins per unique achievement');
mock.mode='mp';recordEscape.call(mock,'level10');
assert.equal(Object.keys(saved.data.ach).length,5,'multiplayer level exits do not award solo escape achievements');
recordEscape.call(mock,'unknown');
assert.equal(Object.keys(saved.data.ach).length,5,'unknown levels do not award achievements');
mock.recordAchievement.call(mock,47,'invalid');
assert.equal(Object.keys(saved.data.ach).length,5,'out-of-range achievements are rejected');
assert.ok(source.includes("+'/'+names.length"), 'achievement UI displays achievement progress');
console.log('PASS: 35 unique level escape mappings; 46 achievements; difficulty-based rewards, eight ending-specific achievements and cumulative rainbow suit unlock verified; duplicate, unknown and out-of-range awards rejected.');
